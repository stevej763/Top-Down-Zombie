/**
 * Records a reference run of the TS sim for the Java sim to replay (SimParityTest). Both run the
 * same bot with the same seed and must produce the same states. Re-run after any gameplay change:
 *   npm run parity
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { GameSim } from '../src/sim/GameSim';
import { NO_INPUT, type PlayerInput } from '../src/sim/input';
import type { Zombie } from '../src/sim/Zombie';

const ROOT = new URL('../../', import.meta.url).pathname;
const OUT = `${ROOT}server/sim/src/test/resources/parity.txt`;
const DT = 1 / 60;
const SEED = 42;
const TICKS = 60 * 120;
const EVERY = 300;

/** Must match GameSimTest.bot in Java exactly. */
function bot(s: GameSim): PlayerInput {
  const p = s.player;
  let target: Zombie | null = null;
  let best = Infinity;
  for (const z of s.zombies) {
    const d = Math.hypot(z.x - p.x, z.y - p.y);
    if (d < best && s.map.hasLOS(p.x, p.y, z.x, z.y)) {
      best = d;
      target = z;
    }
  }
  const w = p.weapon;
  const inp = { ...NO_INPUT };
  if (target) {
    inp.aim = Math.atan2(target.y - p.y, target.x - p.x);
    const dry = w.mag === 0 && w.reserve === 0;
    if (target.state === 'inside' && (best < 55 || dry)) {
      inp.knife = best < 55;
      if (dry && best > 40) {
        inp.moveX = Math.sign(Math.round((target.x - p.x) / 8));
        inp.moveY = Math.sign(Math.round((target.y - p.y) / 8));
      }
      return inp;
    }
    inp.fireHeld = true;
    inp.firePressed = s.time % 0.3 < DT * 1.5;
    inp.reload = w.mag === 0;
    return inp;
  }
  const b = s.barricades.filter((b) => s.openRooms.has(b.def.room)).sort((a, b) => a.planks - b.planks)[0];
  const dx = b.insidePoint.x - p.x;
  const dy = b.insidePoint.y - p.y;
  const far = Math.hypot(dx, dy) > 20;
  if (far) {
    inp.moveX = Math.sign(Math.round(dx / 8));
    inp.moveY = Math.sign(Math.round(dy / 8));
  }
  inp.interactHeld = !far;
  inp.reload = w.mag < w.magSize;
  return inp;
}

const f = (n: number, d: number) => n.toFixed(d);
const line = (s: GameSim) =>
  `r${s.rounds.round} k${s.kills} p${s.economy.points} hp${f(s.player.hp, 6)} x${f(s.player.x, 6)} y${f(s.player.y, 6)} z=` +
  s.zombies.map((z) => `${z.id}:${f(z.x, 6)},${f(z.y, 6)},${f(z.hp, 3)}`).join(';');

const out = [`# Generated by client/scripts/parity.ts (npm run parity); replayed by SimParityTest. seed=${SEED}`];
for (const map of ['house', 'cabin']) {
  const s = new GameSim(JSON.parse(readFileSync(`${ROOT}maps/${map}.json`, 'utf8')), SEED);
  for (let i = 0; i < TICKS && !s.over; i++) {
    s.step(DT, bot(s));
    s.events.length = 0;
    if (i % EVERY === 0) out.push(`${map} ${i} ${line(s)}`);
  }
  out.push(`${map} end ${line(s)}`);
}
writeFileSync(OUT, out.join('\n') + '\n');
console.log(`Wrote ${out.length - 1} states to ${OUT}`);
